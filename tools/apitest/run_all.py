#!/usr/bin/env python3
"""tools/apitest/run_all.py -- matrix driver for the Windows CUDA API diff test.

Runs every flex_apitest scenario against the shipped FleX DLLs (golden) and the
recon DLLs, one process per implementation, then compares the record captures
with compare.py and writes state/reports/apitest.{md,json}.

Steps:
  1. python -I tools/apitest/gen_bindings.py   (regenerates flex_api.h)
  2. build work/apitest-build/flex_apitest.exe if missing (cmake+ninja under
     vcvars64 via a generated work/-only .bat wrapper; MSVC cl required)
  3. discover scenarios via `flex_apitest.exe --list`
  4. scratch dir per side: work/apitest/shipped (shipped DLLs + cudart) and
     work/apitest/recon (recon/build-win DLLs); run every scenario on both
     sides, 300 s timeout, a crash/timeout is recorded as data (exit code +
     stderr tail), never fatal to the matrix
  5. compare.py per scenario (shipped side = golden) -> state/reports/apitest.*

A recon side that is not built (no recon/build-win DLLs) is a warning: the
matrix runs shipped-only and the report says so.
"""

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APITEST = Path(__file__).resolve().parent
BUILD_DIR = ROOT / "work" / "apitest-build"
WORK = ROOT / "work" / "apitest"
REPORTS = ROOT / "state" / "reports"
EXE_NAME = "flex_apitest.exe"

TIMEOUT_S = 300

SHIPPED_DLLS = [
    "NvFlexReleaseCUDA_x64.dll",
    "NvFlexExtReleaseCUDA_x64.dll",
    "NvFlexDeviceRelease_x64.dll",
    "cudart64_92.dll",
]
RECON_DLLS = SHIPPED_DLLS[:3]  # recon builds the FleX DLLs, not cudart


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True,
                          cwd=str(ROOT), **kw)


def python():
    return sys.executable


def gen_bindings() -> None:
    r = run([python(), "-I", str(APITEST / "gen_bindings.py")])
    if r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        raise SystemExit(f"run_all: gen_bindings.py failed ({r.returncode})")


def build_exe() -> Path:
    """Build flex_apitest.exe under vcvars via a work/-only .bat wrapper.

    The wrapper clears CC/CXX (the host shell exports clang) and configures
    with the MSVC cl toolchain.  If the build with the real scenario packs
    fails but a work/-only stub pack exists, the build is retried with
    -DFLEX_APITEST_STUB_ONLY=ON and the fallback is recorded loudly.
    """
    exe = BUILD_DIR / EXE_NAME
    bat = BUILD_DIR / "build_apitest.bat"
    bat.parent.mkdir(parents=True, exist_ok=True)
    stub_flag = "" if list(APITEST.glob("*_scenarios.cpp")) else \
        " -DFLEX_APITEST_STUB_ONLY=ON"
    bat.write_text(
        "@echo off\r\n"
        "rem generated by tools/apitest/run_all.py (work/-only)\r\n"
        "set CC=\r\n"
        "set CXX=\r\n"
        "call \"C:\\Program Files\\Microsoft Visual Studio\\18\\Community\\"
        "VC\\Auxiliary\\Build\\vcvars64.bat\" -vcvars_ver=14.44.35207 >nul 2>&1\r\n"
        "cd /d " + str(ROOT) + "\r\n"
        "if exist work\\apitest-build\\CMakeCache.txt goto build\r\n"
        "cmake -S tools\\apitest -B work\\apitest-build -G Ninja "
        "-DCMAKE_BUILD_TYPE=Release" + stub_flag + "\r\n"
        "if errorlevel 1 exit /b 1\r\n"
        ":build\r\n"
        "cmake --build work\\apitest-build\r\n"
        "exit /b %ERRORLEVEL%\r\n",
        encoding="ascii")

    r = run(["cmd", "/c", str(bat)])
    if r.returncode != 0 and not stub_flag:
        # Real packs are mid-edit?  Fall back to the stub pack explicitly.
        print("run_all: WARNING real-pack build failed; retrying with the "
              "work/-only stub pack (FLEX_APITEST_STUB_ONLY=ON)", file=sys.stderr)
        vcvars = ("call \"C:\\Program Files\\Microsoft Visual Studio\\18\\"
                  "Community\\VC\\Auxiliary\\Build\\vcvars64.bat\" "
                  "-vcvars_ver=14.44.35207 >nul 2>&1")
        reconf = BUILD_DIR / "reconf_stub.bat"
        reconf.write_text(
            "@echo off\r\n" + vcvars + "\r\n"
            "cd /d " + str(ROOT) + "\r\n"
            "set CC=\r\nset CXX=\r\n"
            "cmake -S tools\\apitest -B work\\apitest-build -G Ninja "
            "-DCMAKE_BUILD_TYPE=Release -DFLEX_APITEST_STUB_ONLY=ON\r\n"
            "if errorlevel 1 exit /b 1\r\n"
            "cmake --build work\\apitest-build\r\n"
            "exit /b %ERRORLEVEL%\r\n", encoding="ascii")
        r2 = run(["cmd", "/c", str(reconf)])
        if r2.returncode != 0:
            sys.stderr.write(r.stdout + r.stderr + r2.stdout + r2.stderr)
            raise SystemExit("run_all: flex_apitest build failed")
        print("run_all: built with the work/-only stub pack (records below "
              "are pipeline validation, not full API coverage)")
    elif r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        raise SystemExit("run_all: flex_apitest build failed")
    if not exe.exists():
        raise SystemExit("run_all: build reported success but "
                         f"{exe} is missing")
    return exe


def discover_scenarios(exe: Path):
    r = run([str(exe), "--list"])
    if r.returncode != 0:
        raise SystemExit(f"run_all: --list failed ({r.returncode})")
    names = []
    for line in r.stdout.splitlines():
        line = line.strip()
        if line:
            names.append(line.split("\t")[0].split()[0])
    return names


def prepare_side(side: str, exe: Path, dlls):
    """Scratch dir with the exe + this side's DLLs; returns missing pieces."""
    d = WORK / side
    d.mkdir(parents=True, exist_ok=True)
    shutil.copy2(exe, d / EXE_NAME)
    missing = []
    for dll in dlls:
        src = ROOT / "FleX" / "bin" / "win64" / dll if side == "shipped" \
            else ROOT / "recon" / "build-win" / dll
        if src.exists():
            shutil.copy2(src, d / dll)
        else:
            missing.append(dll)
    return d, missing


def run_scenario(side_dir: Path, exe_args, scenario: str):
    cmd = [str(side_dir / EXE_NAME)] + exe_args + \
          ["--scenario", scenario, "--out", str(side_dir)]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True,
                           cwd=str(side_dir), timeout=TIMEOUT_S)
        return {"exit": r.returncode, "stderr_tail": r.stderr[-2000:]}
    except subprocess.TimeoutExpired as e:
        tail = (e.stderr or b"").decode("utf-8", "replace")[-2000:] \
            if isinstance(e.stderr, bytes) else (e.stderr or "")[-2000:]
        return {"exit": None, "timeout": TIMEOUT_S, "stderr_tail": tail}


def main() -> int:
    gen_bindings()
    exe = build_exe()
    scenarios = discover_scenarios(exe)
    print(f"run_all: {len(scenarios)} scenarios: {', '.join(scenarios)}")

    shipped_dir, shipped_missing = prepare_side("shipped", exe, SHIPPED_DLLS)
    recon_dir, recon_missing = prepare_side("recon", exe, RECON_DLLS)
    recon_ok = not recon_missing
    if not recon_ok:
        print("run_all: WARNING recon: not built "
              f"(missing {', '.join(recon_missing)}); shipped-only mode",
              file=sys.stderr)
    if shipped_missing:
        print(f"run_all: WARNING shipped side missing {shipped_missing}",
              file=sys.stderr)

    runs = {}
    for scenario in scenarios:
        entry = {}
        if not shipped_missing:
            args = ["--dll", "NvFlexReleaseCUDA_x64.dll"]
            if "NvFlexExtReleaseCUDA_x64.dll" not in shipped_missing:
                args += ["--ext", "NvFlexExtReleaseCUDA_x64.dll"]
            if "NvFlexDeviceRelease_x64.dll" not in shipped_missing:
                args += ["--device", "NvFlexDeviceRelease_x64.dll"]
            entry["shipped"] = run_scenario(shipped_dir, args, scenario)
        if recon_ok:
            args = ["--dll", "NvFlexReleaseCUDA_x64.dll",
                    "--ext", "NvFlexExtReleaseCUDA_x64.dll",
                    "--device", "NvFlexDeviceRelease_x64.dll"]
            entry["recon"] = run_scenario(recon_dir, args, scenario)
        else:
            entry["recon"] = {"exit": None, "skipped": "recon: not built"}
        runs[scenario] = entry
        for side, r in entry.items():
            code = r.get("exit")
            print(f"run_all:   {scenario} [{side}]: exit={code}")

    # compare: shipped side is golden
    compare_json = WORK / "compare.json"
    verdicts = None
    compare_exit = None
    compare_out = ""
    if recon_ok:
        r = run([python(), "-I", str(APITEST / "compare.py"),
                 str(shipped_dir), str(recon_dir),
                 "--json", str(compare_json)])
        compare_exit = r.returncode
        compare_out = r.stdout
        print(compare_out, end="")
        if compare_json.exists():
            verdicts = json.loads(compare_json.read_text(encoding="utf-8")) \
                .get("scenarios")
    else:
        print("run_all: compare skipped (recon: not built)")

    # ---- report ----
    REPORTS.mkdir(parents=True, exist_ok=True)
    md = []
    md.append("# apitest matrix")
    md.append("")
    md.append(f"* shipped (golden): `{shipped_dir}`"
              + (f"  missing DLLs: {shipped_missing}" if shipped_missing else ""))
    md.append(f"* recon: `{recon_dir}`"
              + ("  **recon: not built**" if not recon_ok else ""))
    md.append("")
    md.append("| scenario | shipped exit | recon exit | verdict |")
    md.append("|---|---|---|---|")
    n_fail = 0
    for scenario in scenarios:
        entry = runs[scenario]
        se = entry["shipped"].get("exit")
        re = entry["recon"].get("exit")
        if verdicts and scenario in verdicts:
            bad = [rn for rn, v in verdicts[scenario].items()
                   if v.get("verdict") in ("mismatch", "missing", "extra")]
            verdict = "match" if not bad else "FAIL: " + ", ".join(bad)
            n_fail += len(bad)
        elif not recon_ok:
            verdict = "no recon run"
        else:
            verdict = "no verdict"
        md.append(f"| {scenario} | {se} | {re} | {verdict} |")
    md.append("")
    if not recon_ok:
        md.append("**recon: not built** — shipped-only mode; every scenario "
                  "still ran against the shipped DLLs (pipeline check).")
    if n_fail:
        md.append(f"**{n_fail} failing records.**")
    (REPORTS / "apitest.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    report_json = {
        "shipped_dir": str(shipped_dir),
        "recon_dir": str(recon_dir),
        "recon_built": recon_ok,
        "scenarios": runs,
        "compare_exit": compare_exit,
        "verdicts": verdicts,
        "failing_records": n_fail,
    }
    (REPORTS / "apitest.json").write_text(
        json.dumps(report_json, indent=2) + "\n", encoding="utf-8")
    print(f"run_all: report -> {REPORTS / 'apitest.md'}")

    if not recon_ok:
        return 0  # shipped-only mode: pipeline ran, nothing to compare yet
    return 1 if n_fail else 0


if __name__ == "__main__":
    sys.exit(main())
