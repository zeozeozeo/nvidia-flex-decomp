def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def generate(out_path: Path) -> None:
    bindings = []
    for header_path, module in HEADERS:
        bindings += extract_bindings(header_path, module,
                                     expect_extern_c=(module != "device"))
    if not bindings:
        raise SystemExit("gen_bindings: no declarations parsed")

    errors = []
    core, ext, device = check_exports(bindings, errors)
    if errors:
        for e in errors:
            print(f"gen_bindings: ERROR {e}", file=sys.stderr)
        raise SystemExit(1)
    # Emission uses only the kept (shipped-exported) bindings.
    bindings = core + ext + device

    binding_lines = []
    table_lines = []
    assert_lines = []
    for b in bindings:
        binding_lines.append(f"// {b.header}:{b.line}"
                             + (" [inline helper, DLL export]" if b.is_inline else ""))
        binding_lines.append(typedef_of(b))
        binding_lines.append(f"inline {b.name}_t {b.name} = nullptr;")
        binding_lines.append("")
        table_lines.append(
            f'    {{"{b.name}", "{b.symbol}", {MODULE_IDS[b.module]}, '
            f'APITEST_TARGET(api::{b.name})}},')
        assert_lines.append(
            f"static_assert(std::is_same<decltype(&::{b.name}), "
            f"api::{b.name}_t>::value,")
        assert_lines.append(
            f'              "apitest: signature drift for {b.name} '
            f'({b.header}:{b.line})");')

    sources = []
    for header_path, module in HEADERS:
        n = len([b for b in bindings if b.module == module])
        sources.append(f"//   {header_path.name:<16} sha256={sha256_of(header_path)} "
                       f"-> {n} bindings ({MODULE_NAMES[MODULE_IDS[module]]})")
    helpers_n = len([b for b in bindings if b.is_inline])
    sources.append(f"//   (of which {helpers_n} are the NV_FLEX_API inline helpers, "
                   f"exported by both core and ext DLLs; bound from core)")

    text = HEADER_TMPL.format(
        sources="\n".join(sources),
        total=len(bindings),
        bindings="\n".join(binding_lines),
        table="\n".join(table_lines),
        asserts="\n".join(assert_lines),
        helpers=HELPERS_SECTION,
    )
    out_path.write_text(text, encoding="utf-8", newline="\n")
    impl_path = out_path.with_name("flex_api_impl.cpp")
    impl_path.write_text(IMPL_TMPL, encoding="utf-8", newline="\n")
    print(f"{out_path}: {len(bindings)} bindings "
          f"(core={len(core)}, ext={len(ext)}, device={len(device)}, "
          f"inline-helpers={helpers_n})")
    print(f"{impl_path}: scenario-helper definition TU")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=str(APITEST / "flex_api.h"),
                    help="output header path (default tools/apitest/flex_api.h)")
    args = ap.parse_args()
    generate(Path(args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
