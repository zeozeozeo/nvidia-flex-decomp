TYPE_KEYWORDS = {
    "const", "volatile", "unsigned", "signed", "long", "short", "int",
    "float", "double", "bool", "void", "char", "wchar_t", "auto",
}
IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

TOKEN_RE = re.compile(
    r'[A-Za-z_][A-Za-z0-9_]*'   # identifier / keyword
    r'|0[xX][0-9a-fA-F]+'       # hex literal
    r'|\d+(?:\.\d+)?'           # decimal literal
    r'|"[^"]*"'                 # string literal (e.g. "C")
    r'|\S'                      # any other single char
)


class ParseError(Exception):
    pass


class Binding:
    __slots__ = ("name", "ret", "params", "module", "is_inline",
                 "header", "line", "symbol")

    def __init__(self, name, ret, params, module, is_inline, header, line):
        self.name = name
        self.ret = ret            # list[str] return-type tokens
        self.params = params      # list[(list[str] type tokens, str|None name)]
        self.module = module
        self.is_inline = is_inline
        self.header = header
        self.line = line
        self.symbol = name        # device bindings override with decorated name


def strip_comments(text: str) -> str:
    """Blank out // and /* */ comments, preserving newlines and offsets."""
    out = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            j = text.find("\n", i)
            if j < 0:
                j = n
            out.append(" " * (j - i))
            i = j
        elif c == "/" and i + 1 < n and text[i + 1] == "*":
            j = text.find("*/", i + 2)
            if j < 0:
                raise ParseError("unterminated block comment")
            out.append("".join(ch if ch == "\n" else " " for ch in text[i:j + 2]))
            i = j + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def tokenize(text: str):
    toks = []
    line = 1
    pos = 0
    for m in TOKEN_RE.finditer(text):
        line += text.count("\n", pos, m.start())
        pos = m.start()
        toks.append((m.group(0), line))
    return toks


def collect_decl(toks, i, depth, extern_stack, header):
    """Gather the tokens of one NV_FLEX_API declaration starting at index i.

    Stops at ';' (plain declaration) or at the matching '}' of an inline
    function body.  Returns (decl_tokens, next_index, in_extern_c).
    """
    in_extern_c = bool(extern_stack) and extern_stack[-1] <= depth
    n = len(toks)
    decl = []
    paren = 0
    body = False
    while i < n:
        tok = toks[i][0]
        if tok == "(":
            paren += 1
        elif tok == ")":
            paren -= 1
        elif tok == ";" and paren == 0:
            return decl, i + 1, in_extern_c
        elif tok == "{" and paren == 0:
            body = True
            break
        decl.append(tok)
        i += 1
        if paren < 0:
            raise ParseError(f"{header}: unbalanced parentheses in declaration")
    if body:
        bdepth = 1
        i += 1
        while i < n and bdepth:
            t = toks[i][0]
            if t == "{":
                bdepth += 1
            elif t == "}":
                bdepth -= 1
            i += 1
        if bdepth:
            raise ParseError(f"{header}: unbalanced inline body")
    else:
        raise ParseError(f"{header}: declaration not terminated")
    return decl, i, in_extern_c


def parse_params(toks, header, name):
    """Split a parameter token list into (type_tokens, name|None) pairs."""
    groups = []
    cur = []
    depth = 0
    for t in toks:
        if t == "(":
            depth += 1
        elif t == ")":
            depth -= 1
        if t == "," and depth == 0:
            groups.append(cur)
            cur = []
        else:
            cur.append(t)
    if cur or groups:
        groups.append(cur)

    params = []
    for g in groups:
        if not g:
            raise ParseError(f"{header}: empty parameter in {name}")
        if "=" in g:
            g = g[:g.index("=")]
            if not g:
                raise ParseError(
                    f"{header}: parameter of {name} is only a default value")
        if "(" in g or ")" in g:
            raise ParseError(
                f"{header}: function-pointer parameter in {name} is not supported")
        if len(g) >= 2 and IDENT_RE.match(g[-1]) and g[-1] not in TYPE_KEYWORDS:
            ptype, pname = g[:-1], g[-1]
        else:
            ptype, pname = g, None
        for bad in ("=", ",", ";", "[", "]"):
            if bad in ptype:
                raise ParseError(
                    f"{header}: unsupported token {bad!r} in parameter type "
                    f"of {name}: {g}")
        params.append((ptype, pname))
    return params


def parse_decl(tokens, module, header, line, in_extern_c, expect_extern_c):
    toks = list(tokens)
    is_inline = False
    if toks and toks[0] == "inline":
        is_inline = True
        toks = toks[1:]
    if "(" not in toks:
        raise ParseError(f"{header}:{line}: no '(' in declaration")
    p = toks.index("(")
    if p < 2:
        raise ParseError(f"{header}:{line}: missing return type or name")
    name = toks[p - 1]
    if not IDENT_RE.match(name) or name in TYPE_KEYWORDS:
        raise ParseError(f"{header}:{line}: bad function name {name!r}")
    ret = toks[:p - 1]
    if not ret:
        raise ParseError(f"{header}:{line}: empty return type of {name}")
    for bad in ("=", ",", ";", "[", "]"):
        if bad in ret:
            raise ParseError(
                f"{header}:{line}: unsupported token {bad!r} in return type "
                f"of {name}: {ret}")

    depth = 0
    end = None
    for k in range(p, len(toks)):
        if toks[k] == "(":
            depth += 1
        elif toks[k] == ")":
            depth -= 1
            if depth == 0:
                end = k
                break
    if end is None:
        raise ParseError(f"{header}:{line}: unbalanced parameter list of {name}")
    trailing = toks[end + 1:]
    if trailing:
        raise ParseError(
            f"{header}:{line}: trailing tokens after parameter list of {name}: "
            f"{trailing}")

    params = parse_params(toks[p + 1:end], header, name)

    if expect_extern_c and not in_extern_c:
        raise ParseError(f"{header}:{line}: {name} is not inside extern \"C\"")
    if not expect_extern_c and in_extern_c:
        raise ParseError(f"{header}:{line}: {name} unexpectedly inside extern \"C\"")

    return Binding(name, ret, params, module, is_inline, header, line)


def extract_bindings(header_path: Path, module: str, expect_extern_c: bool):
    text = strip_comments(
        header_path.read_text(encoding="utf-8", errors="replace"))
    toks = tokenize(text)
    out = []
    extern_stack = []  # brace depths of active extern "C" blocks
    depth = 0
    i = 0
    n = len(toks)
    while i < n:
        tok, ln = toks[i]
        if tok == "#":
            # Preprocessor directive: skip the rest of the line (this also
            # hides NvFlex.h's own "#define NV_FLEX_API ..." block).
            i += 1
            while i < n and toks[i][1] == ln:
                i += 1
            continue
        if (tok == "extern" and i + 2 < n and toks[i + 1][0] == '"C"'
                and toks[i + 2][0] == "{"):
            extern_stack.append(depth + 1)
            depth += 1
            i += 3
            continue
        if tok == "{":
            depth += 1
        elif tok == "}":
            if extern_stack and extern_stack[-1] == depth:
                extern_stack.pop()
            depth -= 1
        elif tok == "NV_FLEX_API":
            decl, i2, in_extern_c = collect_decl(toks, i + 1, depth,
                                                 extern_stack, header_path.name)
            out.append(parse_decl(decl, module, header_path.name, ln,
                                  in_extern_c, expect_extern_c))
            i = i2
            continue
        i += 1
    return out


def join_type(toks) -> str:
    """Join type tokens into canonical C++ spelling ('NvFlexSolver**')."""
    s = ""
    for t in toks:
        if t in ("*", "&"):
            s += t
        elif s.endswith("*") or s.endswith("&"):
            s += " " + t
        else:
            s += (" " if s else "") + t
    return s


def typedef_of(b: Binding) -> str:
    ps = []
    for ptype, pname in b.params:
        s = join_type(ptype)
        if pname:
            s += " " + pname
        ps.append(s)
    params = ", ".join(ps) if ps else "void"
    return f"using {b.name}_t = {join_type(b.ret)} (*)({params});"


def decl_of(b: Binding) -> str:
    ps = []
    for ptype, pname in b.params:
        s = join_type(ptype)
        if pname:
            s += " " + pname
        ps.append(s)
    params = ", ".join(ps) if ps else "void"
    return f"{join_type(b.ret)} {b.name}({params})"


def def_plain_name(decorated: str) -> str:
    """'?NvFlexDeviceCreateCudaContext@@YA_NH@Z' -> 'NvFlexDeviceCreateCudaContext'."""
    if decorated.startswith("?"):
        return decorated[1:decorated.index("@@")]
    return decorated


def check_exports(bindings, errors):
    """Pin the binding surface to the shipped export sets.

    The shipped DLLs are the authority: a header decl with NV_FLEX_API that the
    shipped binary does not export (NvFlex.h declares NvFlexWait,
    NvFlexCopySolver and NvFlexGetDataAftermath, none of which the shipped core
    DLL exports) gets NO binding -- there is nothing to GetProcAddress.  Every
    remaining decl must match its frozen .def exactly, or generation fails.
    """
    dumpbin = gen_exports.find_dumpbin()
    shipped = {}
    for dll_name, target in gen_exports.TARGETS:
        dll = ROOT / "FleX" / "bin" / "win64" / dll_name
        names = set(gen_exports.parse_exports(dumpbin, dll))
        def_names = set(gen_exports.read_def(
            ROOT / "recon" / "win32" / f"{target}.def"))
        if names != def_names:
            errors.append(
                f"{target}.def has drifted from shipped {dll_name}: "
                f"missing={sorted(names - def_names)} "
                f"extra={sorted(def_names - names)}")
        shipped[target] = names

    # Drop header decls the shipped binaries do not export (recorded, loud).
    kept = []
    for b in bindings:
        target = {"core": "nvflex", "ext": "nvflexext",
                  "device": "nvflexdevice"}[b.module]
        if b.module == "device":
            match = [n for n in shipped[target] if def_plain_name(n) == b.name]
        else:
            match = [n for n in shipped[target] if n == b.name]
        if not match:
            print(f"gen_bindings: note {b.header}:{b.line}: {b.name} is declared "
                  f"in the public header but not exported by the shipped DLL; "
                  f"no binding emitted", file=sys.stderr)
            continue
        if b.module == "device":
            b.symbol = match[0]
        kept.append(b)
    bindings = kept

    core = [b for b in bindings if b.module == "core"]
    ext = [b for b in bindings if b.module == "ext"]
    device = [b for b in bindings if b.module == "device"]

    helpers = {b.name for b in core if b.is_inline}
    core_plain = {b.name for b in core if not b.is_inline}
    ext_plain = {b.name for b in ext}
    dev_plain = {b.name for b in device}

    if helpers != {
        "NvFlexMakePhase", "NvFlexMakePhaseWithChannels",
        "NvFlexMakeShapeFlags", "NvFlexMakeShapeFlagsWithChannels",
    }:
        errors.append(
            f"unexpected NV_FLEX_API inline set in NvFlex.h: {sorted(helpers)}")

    def compare(def_names, expected, label):
        missing = sorted(set(def_names) - expected)
        extra = sorted(expected - set(def_names))
        if missing:
            errors.append(f"{label}: exports without a parsed decl: {missing}")
        if extra:
            errors.append(f"{label}: parsed decls missing from exports: {extra}")

    compare(shipped["nvflex"], core_plain | helpers, "nvflex.def vs NvFlex.h")
    compare(shipped["nvflexext"], ext_plain | helpers, "nvflexext.def vs NvFlexExt.h")
    compare({def_plain_name(n) for n in shipped["nvflexdevice"]}, dev_plain,
            "nvflexdevice.def vs NvFlexDevice.h")

    seen = {}
    for b in bindings:
        if b.name in seen:
            errors.append(f"duplicate binding name {b.name} "
                          f"({seen[b.name]} and {b.header}:{b.line})")
        seen[b.name] = f"{b.header}:{b.line}"

    return core, ext, device


