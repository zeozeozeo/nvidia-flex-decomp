#!/usr/bin/env python3
"""tools/apitest/gen_bindings.py -- generate flex_api.h from the FleX public headers.

Parses FleX/include/NvFlex.h, NvFlexExt.h and NvFlexDevice.h and emits
tools/apitest/flex_api.h:

  * namespace `api`: one C++17 inline function-pointer variable per exported
    entry point of the three shipped DLLs, plus a `<Name>_t` typedef with the
    exact header signature (const/volatile/pointer syntax preserved, default
    arguments stripped).  The 4 `NV_FLEX_API inline` helpers (NvFlexMakePhase,
    NvFlexMakePhaseWithChannels, NvFlexMakeShapeFlags,
    NvFlexMakeShapeFlagsWithChannels) are DLL exports, so they get bindings
    too; scenarios must use the `api::` bindings to exercise the DLL-exported
    path, not the header-inline copies.
  * an ApiModuleInfo table (binding name, GetProcAddress symbol, owning module)
    and inline resolve_api(core, ext, device): returns false and records the
    missing names when a *loaded* module fails to resolve any binding.  A null
    module argument means "not provided": bindings for it stay null without
    failing resolution, and the runner aborts a scenario that touches them.
  * compile-time static_asserts pinning every typedef to the exact decltype of
    the public declaration, so signature drift fails the build.
  * the runner-support section: error-callback capture (error.<n> records),
    ScenarioAbort, and the scenario seed.
  * the shared scenario helpers declared at the bottom of scenario.h
    (makeSolver, destroySolver, makeBuffer, writeBuffer, readBuffer), with
    their text in flex_api.h under APITEST_IMPLEMENT_HELPERS.  They cannot be
    plain inline functions: Ctx is defined in scenario.h *after* it includes
    flex_api.h, so an unguarded inline definition would see an incomplete
    type.  Instead the generator also emits flex_api_impl.cpp, a one-TU
    definition unit that includes scenario.h first and then re-includes
    flex_api.h with APITEST_IMPLEMENT_HELPERS defined; the CMake target
    compiles it and the runner plus every pack link against those symbols.

Any parse failure is a hard error.  The parsed surface is machine-checked
against the frozen export lists in recon/win32/*.def (generated by
gen_exports.py):

    nvflex.def       == NvFlex.h non-inline decls + the 4 inline helpers
    nvflexext.def    == NvFlexExt.h decls + the same 4 inline helpers
    nvflexdevice.def == NvFlexDevice.h decls (decorated C++ names, compared
                        by plain name)

Usage: python tools/apitest/gen_bindings.py [--out FILE]
"""

