"""CUDA-runtime and data stub generation for the analysis link.

Method (ground truth, not guesswork):

1. Trial-link the archive into a throwaway ``.so`` with
   ``--unresolved-symbols=ignore-all``.
2. Ask the dynamic symbol table which symbols remain undefined.  That set is
   exactly what the loader would fail on (libc/libstdc++/libm symbols are
   already resolved by the driver and never appear).
3. Classify each remaining symbol as code or data from the objects'
   relocations: ``R_X86_64_PLT32``/``PC32`` imply a call target, everything
   else is treated as storage.
4. Emit C stubs and compile them with ``gcc -fno-builtin -ffreestanding`` so
   that names such as ``ceilf`` do not collide with compiler builtins.

Stubs are per library: a symbol undefined in ``NvFlexReleaseCUDA`` may be
defined in ``NvFlexExtReleaseCUDA`` (``seed1``/``seed2``), so a single global
stub file produces multiple-definition errors.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

from . import ARCHIVES, FLEX, OBJ, TOOLS, WORK
from .extract import LINK_LIBS
from .util import ensure, jwrite, run, run_ok

STUB_FUNC = "unsigned long {sym}(void) {{ return 0; }}\n"
STUB_DATA = "unsigned long {sym};\n"

RELOC_RE = re.compile(r"\s(R_X86_64_\w+)\s+[0-9a-fA-F]+\s+(\S+)")
CODE_RELOCS = {"R_X86_64_PLT32", "R_X86_64_PC32", "R_X86_64_PC64"}


def _classify(objects: list[Path]) -> dict[str, str]:
    """symbol -> 'code' | 'data' from relocation records."""
    kind: dict[str, str] = {}
    for obj in objects:
        out = run(["readelf", "-rW", str(obj)])
        for line in out.splitlines():
            m = RELOC_RE.search(line)
            if not m:
                continue
            rtype, sym = m.group(1), m.group(2)
            if sym.endswith("@"):
                sym = sym[:-1]
            if rtype in CODE_RELOCS:
                kind[sym] = "code"
            else:
                kind.setdefault(sym, "data")
    return kind


LINK_UNRESOLVED = re.compile(r"undefined reference to [`'\u2018]([^'`\u2019]+)")


def _link_undefined(cmd: list[str]) -> list[str] | None:
    """Undefined symbols reported by the linker, or None if the link succeeded."""
    p = subprocess.run(cmd, capture_output=True, text=True, errors="replace")
    if p.returncode == 0:
        return []
    names = set()
    for line in p.stderr.splitlines():
        m = LINK_UNRESOLVED.search(line)
        if m:
            names.add(m.group(1))
    return sorted(names) if names else None


def _still_undefined(so: Path) -> list[str]:
    """Strong undefined symbols only; weak refs resolve (or stay null) at load."""
    names = []
    for line in run(["nm", "-D", "--undefined-only", str(so)]).splitlines():
        parts = line.split()
        if len(parts) < 2 or parts[-2] not in ("U",):
            continue
        name = parts[-1]
        if name.endswith("@"):
            name = name[:-1]
        # versioned references like foo@GLIBC_2.2.5 keep only the base name
        name = name.split("@", 1)[0]
        if name:
            names.append(name)
    return sorted(set(names))


def _objects_for(lib: str, variant: str) -> list[Path]:
    base = OBJ / variant / ("NvFlexReleaseCUDA_x64" if False else "")
    return sorted(base.parent.glob("*/*.o"))


def generate(variant: str = "rel") -> dict:
    pargen = TOOLS / "parity" / "gen"
    ensure(pargen)
    report = {"variant": variant, "libraries": {}, "cuda": 0}

    all_objs = [p for p in (OBJ / variant).glob("*/*.o")]
    kinds = _classify(all_objs)

    for lib, fname in ARCHIVES[variant].items():
        archive = FLEX / "lib" / "linux64" / fname
        if not archive.exists():
            continue
        trial = WORK / "gen" / f"trial_{lib}_{variant}.so"
        ensure(trial.parent)
        trial_cmd = [
            "g++", "-shared", "-fPIC", "-o", str(trial),
            "-Wl,--whole-archive", str(archive), "-Wl,--no-whole-archive",
            "-Wl,--no-undefined",
            *LINK_LIBS,
        ]
        missing = _link_undefined(trial_cmd)
        if missing is None:
            report["libraries"][lib] = {"error": "trial link failed without undefined refs",
                                        "archive": fname}
            continue

        code = [s for s in missing if kinds.get(s) == "code"]
        data = [s for s in missing if kinds.get(s) != "code"]

        lines = [f"/* generated by flexkit stubs ({variant}:{fname}) */"]
        lines += [STUB_DATA.format(sym=s) for s in data]
        lines += [STUB_FUNC.format(sym=s) for s in code]
        src = pargen / f"data_stubs_{lib}.c"
        src.write_text("\n".join(lines) + "\n")
        obj = pargen / f"data_stubs_{lib}.o"
        ok = run_ok(["gcc", "-O0", "-w", "-fPIC", "-fno-builtin", "-ffreestanding",
                     "-fno-stack-protector", "-c", "-o", str(obj), str(src)])
        report["libraries"][lib] = {
            "archive": fname,
            "undefined": len(missing),
            "code": len(code),
            "data": len(data),
            "compiled": ok,
            "symbols": sorted(missing),
        }
        report["cuda"] = len([s for s in kinds if s.startswith(("cuda", "cu", "__cuda", "nvidia"))])

    jwrite(WORK / "stubs.json", report)
    return {"variant": variant,
            "libraries": {k: {"code": v.get("code"), "data": v.get("data"),
                              "compiled": v.get("compiled")}
                          for k, v in report["libraries"].items()}}
